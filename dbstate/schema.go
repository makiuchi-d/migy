package dbstate

import (
	"database/sql"
	"errors"
	"fmt"
	"strings"

	"github.com/jmoiron/sqlx"
)

var ErrNoMigrationTable = errors.New("no '_migrations' table")

// Table is a table definition reconstructed from the system catalogs.
// PostgreSQL has no "SHOW CREATE TABLE", so Create is assembled by buildCreate.
type Table struct {
	Name        string
	Columns     []*Column
	Constraints []*Constraint
	Indexes     []string // CREATE INDEX statements not backed by a constraint
	Refs        []string // tables referenced by foreign keys
	Create      string
}

// Column is a column definition. Identifiers are already quoted by quote_ident.
type Column struct {
	Table     string         `db:"table"`
	Name      string         `db:"name"`
	Type      string         `db:"type"`
	NotNull   bool           `db:"not_null"`
	Identity  string         `db:"identity"` // "" | "a" (always) | "d" (by default)
	Generated bool           `db:"generated"`
	Default   sql.NullString `db:"default_expr"`
}

// Def returns the column definition of a CREATE TABLE statement.
func (c *Column) Def() string {
	var b strings.Builder
	fmt.Fprintf(&b, "%s %s", c.Name, c.Type)
	switch c.Identity {
	case "a":
		b.WriteString(" GENERATED ALWAYS AS IDENTITY")
	case "d":
		b.WriteString(" GENERATED BY DEFAULT AS IDENTITY")
	}
	if c.Default.Valid {
		if c.Generated {
			fmt.Fprintf(&b, " GENERATED ALWAYS AS (%s) STORED", c.Default.String)
		} else {
			fmt.Fprintf(&b, " DEFAULT %s", c.Default.String)
		}
	}
	if c.NotNull {
		b.WriteString(" NOT NULL")
	}
	return b.String()
}

// Constraint is a table constraint. Def comes from pg_get_constraintdef.
type Constraint struct {
	Table    string         `db:"table"`
	Name     string         `db:"name"`
	Def      string         `db:"def"`
	RefTable sql.NullString `db:"ref_table"`
}

type index struct {
	Table string `db:"table"`
	Def   string `db:"def"`
}

// quoteIdent quotes an identifier as PostgreSQL does.
func quoteIdent(name string) string {
	return `"` + strings.ReplaceAll(name, `"`, `""`) + `"`
}

// buildCreate assembles a CREATE TABLE statement from the catalog rows.
func buildCreate(t *Table) string {
	defs := make([]string, 0, len(t.Columns)+len(t.Constraints))
	for _, c := range t.Columns {
		defs = append(defs, "    "+c.Def())
	}
	for _, c := range t.Constraints {
		defs = append(defs, fmt.Sprintf("    CONSTRAINT %s %s", c.Name, c.Def))
	}
	return fmt.Sprintf("CREATE TABLE %s (\n%s\n)", quoteIdent(t.Name), strings.Join(defs, ",\n"))
}

const qHasMigrationTable = `
SELECT EXISTS (
  SELECT 1 FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = current_schema() AND c.relname = '_migrations' AND c.relkind = 'r')`

func HasMigrationTable(db *sqlx.DB) error {
	var ok bool
	if err := db.Get(&ok, qHasMigrationTable); err != nil {
		return err
	}
	if !ok {
		return ErrNoMigrationTable
	}
	return nil
}

const qTables = `
SELECT c.relname
  FROM pg_class c
  JOIN pg_namespace n ON n.oid = c.relnamespace
 WHERE n.nspname = current_schema() AND c.relkind = 'r' AND c.relpersistence = 'p'
 ORDER BY c.relname`

const qColumns = `
SELECT c.relname AS "table",
       quote_ident(a.attname) AS name,
       format_type(a.atttypid, a.atttypmod) AS type,
       a.attnotnull AS not_null,
       a.attidentity AS identity,
       a.attgenerated <> '' AS generated,
       pg_get_expr(ad.adbin, ad.adrelid) AS default_expr
  FROM pg_class c
  JOIN pg_namespace n ON n.oid = c.relnamespace
  JOIN pg_attribute a ON a.attrelid = c.oid
  LEFT JOIN pg_attrdef ad ON ad.adrelid = a.attrelid AND ad.adnum = a.attnum
 WHERE n.nspname = current_schema() AND c.relkind = 'r' AND c.relpersistence = 'p'
   AND a.attnum > 0 AND NOT a.attisdropped
 ORDER BY c.relname, a.attnum`

const qConstraints = `
SELECT c.relname AS "table",
       quote_ident(con.conname) AS name,
       pg_get_constraintdef(con.oid) AS def,
       fc.relname AS ref_table
  FROM pg_constraint con
  JOIN pg_class c ON c.oid = con.conrelid
  JOIN pg_namespace n ON n.oid = c.relnamespace
  LEFT JOIN pg_class fc ON fc.oid = con.confrelid
 WHERE n.nspname = current_schema() AND con.contype IN ('p', 'u', 'f', 'c', 'x')
 ORDER BY c.relname, con.contype, con.conname`

const qIndexes = `
SELECT c.relname AS "table",
       pg_get_indexdef(i.indexrelid) AS def
  FROM pg_index i
  JOIN pg_class ic ON ic.oid = i.indexrelid
  JOIN pg_class c ON c.oid = i.indrelid
  JOIN pg_namespace n ON n.oid = c.relnamespace
 WHERE n.nspname = current_schema() AND c.relkind = 'r' AND c.relpersistence = 'p'
   AND NOT EXISTS (SELECT 1 FROM pg_constraint con WHERE con.conindid = i.indexrelid)
 ORDER BY c.relname, ic.relname`

// GetTables returns table informations, ordered so that a table always
// appears after the tables it references.
func GetTables(db *sqlx.DB) ([]*Table, error) {
	var names []string
	if err := db.Select(&names, qTables); err != nil {
		return nil, err
	}

	tblmap := make(map[string]*Table, len(names))
	for _, n := range names {
		tblmap[n] = &Table{Name: n}
	}

	var cols []*Column
	if err := db.Select(&cols, qColumns); err != nil {
		return nil, err
	}
	for _, c := range cols {
		if t, ok := tblmap[c.Table]; ok {
			t.Columns = append(t.Columns, c)
		}
	}

	var cons []*Constraint
	if err := db.Select(&cons, qConstraints); err != nil {
		return nil, err
	}
	for _, c := range cons {
		t, ok := tblmap[c.Table]
		if !ok {
			continue
		}
		t.Constraints = append(t.Constraints, c)
		if r := c.RefTable; r.Valid && r.String != c.Table {
			if _, ok := tblmap[r.String]; ok && !contains(t.Refs, r.String) {
				t.Refs = append(t.Refs, r.String)
			}
		}
	}

	var idxs []*index
	if err := db.Select(&idxs, qIndexes); err != nil {
		return nil, err
	}
	for _, i := range idxs {
		if t, ok := tblmap[i.Table]; ok {
			t.Indexes = append(t.Indexes, i.Def)
		}
	}

	for _, t := range tblmap {
		t.Create = buildCreate(t)
	}

	return sortTables(names, tblmap)
}

func contains(ss []string, s string) bool {
	for _, v := range ss {
		if v == s {
			return true
		}
	}
	return false
}

// sortTables orders the tables by their foreign key dependencies.
func sortTables(names []string, tblmap map[string]*Table) ([]*Table, error) {
	tbls := make([]*Table, 0, len(names))
	done := make(map[string]struct{}, len(names))
	pendings := make(map[string][]*Table)

	var appendTable func(t *Table) bool
	appendTable = func(t *Table) bool {
		for _, rt := range t.Refs {
			if _, ok := done[rt]; !ok {
				return false
			}
		}
		tbls = append(tbls, t)
		done[t.Name] = struct{}{}
		for _, pt := range pendings[t.Name] {
			appendTable(pt)
		}
		delete(pendings, t.Name)
		return true
	}

	for _, n := range names {
		t := tblmap[n]
		if appendTable(t) {
			continue
		}
		for _, rt := range t.Refs {
			if _, ok := done[rt]; !ok {
				pendings[rt] = append(pendings[rt], t)
			}
		}
	}

	if len(tbls) != len(names) {
		var p []string
		for _, n := range names {
			if _, ok := done[n]; !ok {
				p = append(p, n)
			}
		}
		return nil, fmt.Errorf("pending tables: %v", strings.Join(p, ", "))
	}

	return tbls, nil
}

// Sequence is a sequence not owned by an identity column
// (identity sequences are created by the column definition itself).
type Sequence struct {
	Name        string         `db:"name"`
	Type        string         `db:"type"`
	Start       int64          `db:"start"`
	Increment   int64          `db:"increment"`
	Min         int64          `db:"min"`
	Max         int64          `db:"max"`
	Cache       int64          `db:"cache"`
	Cycle       bool           `db:"cycle"`
	OwnerTable  sql.NullString `db:"owner_table"`
	OwnerColumn sql.NullString `db:"owner_column"`
	Create      string
}

// OwnedBy returns the ALTER SEQUENCE statement that ties the sequence
// to its column, or "" when the sequence is standalone.
func (s *Sequence) OwnedBy() string {
	if !s.OwnerTable.Valid || !s.OwnerColumn.Valid {
		return ""
	}
	return fmt.Sprintf("ALTER SEQUENCE %s OWNED BY %s.%s",
		quoteIdent(s.Name), quoteIdent(s.OwnerTable.String), s.OwnerColumn.String)
}

func buildCreateSequence(s *Sequence) string {
	var b strings.Builder
	fmt.Fprintf(&b, "CREATE SEQUENCE %s AS %s", quoteIdent(s.Name), s.Type)
	fmt.Fprintf(&b, " START WITH %d INCREMENT BY %d", s.Start, s.Increment)
	fmt.Fprintf(&b, " MINVALUE %d MAXVALUE %d CACHE %d", s.Min, s.Max, s.Cache)
	if s.Cycle {
		b.WriteString(" CYCLE")
	}
	return b.String()
}

const qSequences = `
SELECT c.relname AS name,
       format_type(s.seqtypid, NULL) AS type,
       s.seqstart AS start, s.seqincrement AS increment,
       s.seqmin AS min, s.seqmax AS max, s.seqcache AS cache, s.seqcycle AS cycle,
       tc.relname AS owner_table,
       quote_ident(a.attname) AS owner_column
  FROM pg_sequence s
  JOIN pg_class c ON c.oid = s.seqrelid
  JOIN pg_namespace n ON n.oid = c.relnamespace
  LEFT JOIN pg_depend d ON d.classid = 'pg_class'::regclass AND d.objid = c.oid
                       AND d.refclassid = 'pg_class'::regclass AND d.deptype IN ('a', 'i')
  LEFT JOIN pg_class tc ON tc.oid = d.refobjid
  LEFT JOIN pg_attribute a ON a.attrelid = d.refobjid AND a.attnum = d.refobjsubid
 WHERE n.nspname = current_schema()
   AND coalesce(a.attidentity, '') = ''
 ORDER BY c.relname`

// GetSequences returns the sequences that have to be created explicitly.
func GetSequences(db *sqlx.DB) ([]*Sequence, error) {
	var seqs []*Sequence
	if err := db.Select(&seqs, qSequences); err != nil {
		return nil, err
	}
	for _, s := range seqs {
		s.Create = buildCreateSequence(s)
	}
	return seqs, nil
}

// SequenceValue is the current counter of a sequence, identity ones included.
type SequenceValue struct {
	Name     string
	Last     int64 `db:"last_value"`
	IsCalled bool  `db:"is_called"`
}

const qSequenceNames = `
SELECT c.relname
  FROM pg_class c
  JOIN pg_namespace n ON n.oid = c.relnamespace
 WHERE n.nspname = current_schema() AND c.relkind = 'S'
 ORDER BY c.relname`

// GetSequenceValues returns the current counter of every sequence.
// The value is read from the sequence itself: deriving it from the table data
// would lose a counter set by setval or advanced past the rows.
func GetSequenceValues(db *sqlx.DB) ([]*SequenceValue, error) {
	var names []string
	if err := db.Select(&names, qSequenceNames); err != nil {
		return nil, err
	}

	vals := make([]*SequenceValue, 0, len(names))
	for _, n := range names {
		v := SequenceValue{Name: n}
		q := fmt.Sprintf("SELECT last_value, is_called FROM %s", quoteIdent(n))
		if err := db.Get(&v, q); err != nil {
			return nil, err
		}
		vals = append(vals, &v)
	}

	return vals, nil
}
